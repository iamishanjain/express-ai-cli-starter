import fs from "node:fs/promises";
import path from "node:path";
import type { DatabaseChoice, LanguageChoice, ProjectSpec } from "../types/spec.js";

export interface RenderOptions {
  projectPath: string;
  projectName: string;
  language: LanguageChoice;
  database: DatabaseChoice;
  spec?: ProjectSpec;
}

export async function renderProject(options: RenderOptions): Promise<void> {
  const { projectPath, projectName, language, database, spec } = options;
  const isTs = language === "typescript";
  const ext = isTs ? "ts" : "js";
  const sourceDir = path.join(projectPath, "src");

  await fs.mkdir(path.join(sourceDir, "generated"), { recursive: true });
  for (const folder of ["controllers", "routes", "models", "services", "middlewares", "config", "validators", "utils"]) {
    await fs.mkdir(path.join(sourceDir, folder), { recursive: true });
    await fs.writeFile(path.join(sourceDir, folder, `index.${ext}`), "// Add module code here.\n");
  }

  const packageJson = {
    name: projectName,
    version: "1.0.0",
    private: true,
    type: "module",
    scripts: isTs
      ? { dev: "tsx watch src/server.ts", build: "tsc -p tsconfig.json", start: "node dist/server.js", typecheck: "tsc --noEmit" }
      : { dev: "nodemon src/server.js", start: "node src/server.js" },
    dependencies: {
      express: "^5.0.0",
      dotenv: "^16.4.0",
      cors: "^2.8.5",
      helmet: "^8.0.0",
      ...(database === "postgresql" ? { pg: "^8.0.0" } : {}),
      ...(database === "mysql" ? { mysql2: "^3.0.0" } : {}),
      ...(database === "mongodb" ? { mongoose: "^8.0.0" } : {})
    },
    devDependencies: {
      ...(isTs ? { typescript: "^5.7.0", tsx: "^4.0.0", "@types/node": "^22.0.0", "@types/express": "^5.0.0", "@types/cors": "^2.8.0" } : { nodemon: "^3.0.0" })
    }
  };

  await fs.writeFile(path.join(projectPath, "package.json"), JSON.stringify(packageJson, null, 2) + "\n");
  await fs.writeFile(path.join(projectPath, ".gitignore"), "node_modules/\ndist/\n.env\nlogs/\n");
  await fs.writeFile(path.join(projectPath, ".env.example"), `PORT=3000\nNODE_ENV=development\n${database === "postgresql" || database === "mysql" ? "DB_HOST=localhost\nDB_PORT=\nDB_USER=\nDB_PASSWORD=\nDB_NAME=\n" : ""}${database === "mongodb" ? "MONGO_URI=mongodb://localhost:27017/app\n" : ""}`);

  const appTs = `
import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";

const app = express();
app.use(helmet());
app.use(cors());
app.use(express.json());

app.get("/health", (_req, res) => {
  res.status(200).json({ status: "ok", project: ${JSON.stringify(projectName)} });
});

export default app;
`.trimStart();

  const appJs = `
import "dotenv/config";
import express from "express";
import cors from "cors";
import helmet from "helmet";

const app = express();
app.use(helmet());
app.use(cors());
app.use(express.json());

app.get("/health", (_req, res) => {
  res.status(200).json({ status: "ok", project: ${JSON.stringify(projectName)} });
});

export default app;
`.trimStart();

  const serverTs = `
import app from "./app.js";

const port = Number(process.env.PORT || 3000);
const server = app.listen(port, () => {
  console.log(\`API listening on port \${port}\`);
});

process.on("SIGTERM", () => server.close());
process.on("SIGINT", () => server.close());
`.trimStart();

  const serverJs = `
import app from "./app.js";

const port = Number(process.env.PORT || 3000);
const server = app.listen(port, () => {
  console.log(\`API listening on port \${port}\`);
});

process.on("SIGTERM", () => server.close());
process.on("SIGINT", () => server.close());
`.trimStart();

  await fs.writeFile(path.join(sourceDir, `app.${ext}`), isTs ? appTs : appJs);
  await fs.writeFile(path.join(sourceDir, `server.${ext}`), isTs ? serverTs : serverJs);

  if (isTs) {
    await fs.writeFile(path.join(projectPath, "tsconfig.json"), JSON.stringify({
      compilerOptions: {
        target: "ES2022",
        module: "NodeNext",
        moduleResolution: "NodeNext",
        rootDir: "./src",
        outDir: "./dist",
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true
      },
      include: ["src/**/*.ts"]
    }, null, 2) + "\n");
  }

  if (spec) {
    await fs.writeFile(path.join(sourceDir, "generated", "schema.json"), JSON.stringify(spec, null, 2) + "\n");
  } else {
    await fs.writeFile(path.join(sourceDir, "generated", "schema.json"), JSON.stringify({
      schemaVersion: 1,
      projectSummary: "AI schema generation was skipped.",
      entities: [],
      suggestedModules: [],
      assumptions: ["Run the CLI again with AI enabled to propose a schema."]
    }, null, 2) + "\n");
  }

  await fs.writeFile(path.join(projectPath, "README.md"), `# ${projectName}\n\nGenerated by Express AI CLI.\n\n## Run\n\n\`\`\`bash\ncp .env.example .env\nnpm install\nnpm run dev\n\`\`\`\n\nHealth endpoint: \`GET /health\`\n\nSelected database: **${database}**. Database connection wiring and migrations are not generated in this MVP yet.\n`);
}
